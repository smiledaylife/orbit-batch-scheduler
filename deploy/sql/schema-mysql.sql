-- ---------------------------------------------------------------------------
-- 框架业务表
-- ---------------------------------------------------------------------------

-- 任务配置表（数据库存储模式的数据源，动态增删改）
CREATE TABLE IF NOT EXISTS t_job_config (
    id                BIGINT       AUTO_INCREMENT PRIMARY KEY,
    task_name         VARCHAR(128) NOT NULL COMMENT '任务唯一名',
    task_group        VARCHAR(64)  DEFAULT 'ORBIT' COMMENT '任务分组',
    description       VARCHAR(512) COMMENT '任务描述',
    cron_expression   VARCHAR(64) COMMENT 'Quartz Cron；空=仅手动触发',
    dispatch_type     VARCHAR(16)  NOT NULL DEFAULT 'LOCAL' COMMENT 'LOCAL/HTTP',
    http_service_name VARCHAR(128) COMMENT 'HTTP派发目标服务（空=全局默认）',
    http_path         VARCHAR(256) COMMENT 'HTTP派发远端执行路径（空=全局默认）',
    timeout_seconds   INT          DEFAULT 300 COMMENT '任务超时秒数',
    params            TEXT COMMENT '任务参数 JSON',
    enabled           TINYINT(1)   DEFAULT 1 COMMENT '是否启用',
    version           INT          DEFAULT 1 COMMENT '乐观锁版本',
    created_at        DATETIME(3),
    updated_at        DATETIME(3),
    UNIQUE KEY uk_job_config_task_name (task_name)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '批量任务配置表';

-- 执行日志表
CREATE TABLE IF NOT EXISTS t_job_log (
    id            BIGINT       AUTO_INCREMENT PRIMARY KEY,
    request_id    VARCHAR(64) COMMENT '执行追踪 ID',
    task_name     VARCHAR(128) NOT NULL COMMENT '任务名',
    task_group    VARCHAR(64) COMMENT '任务分组',
    dispatch_type VARCHAR(16) COMMENT 'LOCAL/HTTP',
    dispatch_node VARCHAR(128) COMMENT '发起调度节点',
    worker_node   VARCHAR(128) COMMENT '实际执行节点',
    status        VARCHAR(16)  NOT NULL COMMENT 'RUNNING/SUCCESS/FAILED/SKIPPED',
    start_time    DATETIME(3) COMMENT '开始时间',
    end_time      DATETIME(3) COMMENT '结束时间',
    cost_ms       BIGINT COMMENT '耗时毫秒',
    message       TEXT COMMENT '结果消息/异常信息',
    KEY idx_job_log_task_start (task_name, start_time),
    KEY idx_job_log_status (status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '批量任务执行日志表';

-- 集群锁表（数据库锁模式；时间戳为应用侧毫秒，规避时钟不一致）
CREATE TABLE IF NOT EXISTS t_cluster_lock (
    lock_name   VARCHAR(128) NOT NULL COMMENT '锁名',
    owner       VARCHAR(128) COMMENT '持有节点',
    expire_at   BIGINT COMMENT '过期毫秒时间戳',
    update_time BIGINT COMMENT '最近更新毫秒时间戳',
    PRIMARY KEY (lock_name)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '分布式集群锁表';

